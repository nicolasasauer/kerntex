//! Project folder access: file tree, safe path resolution, text I/O.
//!
//! All paths exchanged with the UI (and later with MCP clients) are
//! *relative* to the project root and use forward slashes. `resolve` is the
//! single gate that turns them into absolute paths and refuses anything
//! that would escape the project folder.

use super::error::{AppError, ErrorSource, Result};
use serde::Serialize;
use std::fs;
use std::path::{Component, Path, PathBuf};

/// Folder KernTeX writes build output into (inside the project).
pub const BUILD_DIR: &str = ".kerntex";

const SKIP_DIRS: &[&str] = &[".git", ".svn", "node_modules", BUILD_DIR, ".vscode", ".idea"];

/// Files LaTeX generates; shown dimmed in the tree, dropped by "clean" export.
pub const AUX_EXTENSIONS: &[&str] = &[
    "aux", "log", "out", "toc", "lof", "lot", "fls", "fdb_latexmk", "synctex", "synctex.gz", "bcf",
    "blg", "run.xml", "nav", "snm", "vrb", "xdv", "idx", "ilg", "ind", "dvi", "glo", "gls", "glg",
    "ist", "acn", "acr", "alg", "loa", "thm",
];

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct FileNode {
    pub name: String,
    /// Relative path with forward slashes, e.g. `chapters/intro.tex`.
    pub path: String,
    pub is_dir: bool,
    /// Generated by LaTeX (aux, log, ...).
    pub generated: bool,
    pub children: Vec<FileNode>,
}

#[derive(Debug, Clone, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct ProjectInfo {
    pub root: String,
    pub name: String,
    pub tree: Vec<FileNode>,
    /// Best guess for the root document, relative path.
    pub main_file: Option<String>,
}

pub fn is_generated(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    AUX_EXTENSIONS.iter().any(|ext| lower.ends_with(&format!(".{ext}")))
}

/// Turns a project-relative path into an absolute one, rejecting absolute
/// paths and `..` so nothing outside the project can be touched.
pub fn resolve(root: &Path, rel: &str) -> Result<PathBuf> {
    let rel_path = Path::new(rel);
    let mut out = root.to_path_buf();
    for comp in rel_path.components() {
        match comp {
            Component::Normal(c) => out.push(c),
            Component::CurDir => {}
            _ => {
                return Err(AppError::new(ErrorSource::App, "Path outside the project was refused")
                    .detail(rel.to_string())
                    .hint("KernTeX only reads and writes files inside the open project folder. Use a path relative to the project root."))
            }
        }
    }
    Ok(out)
}

pub fn to_rel(root: &Path, abs: &Path) -> Option<String> {
    let rel = abs.strip_prefix(root).ok()?;
    Some(rel.components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/"))
}

pub fn open(root: &Path) -> Result<ProjectInfo> {
    let meta = fs::metadata(root).map_err(|e| AppError::io("open the project folder", root, e))?;
    if !meta.is_dir() {
        return Err(AppError::new(ErrorSource::FileSystem, "That's a file, not a folder")
            .detail(root.display().to_string())
            .hint("Open the folder that contains your .tex files, or import a .zip via “Import ZIP”."));
    }
    let tree = read_tree(root)?;
    let main_file = detect_main(root, &tree);
    Ok(ProjectInfo {
        root: root.display().to_string(),
        name: root.file_name().map(|n| n.to_string_lossy().into_owned()).unwrap_or_default(),
        tree,
        main_file,
    })
}

pub fn read_tree(root: &Path) -> Result<Vec<FileNode>> {
    walk(root, root, 0)
}

fn walk(root: &Path, dir: &Path, depth: usize) -> Result<Vec<FileNode>> {
    if depth > 12 {
        return Ok(vec![]);
    }
    let entries = fs::read_dir(dir).map_err(|e| AppError::io("read the folder", dir, e))?;
    let mut nodes = Vec::new();
    for entry in entries.flatten() {
        let name = entry.file_name().to_string_lossy().into_owned();
        let path = entry.path();
        let Ok(ft) = entry.file_type() else { continue };
        let is_dir = ft.is_dir();
        if is_dir && (SKIP_DIRS.contains(&name.as_str())) {
            continue;
        }
        let Some(rel) = to_rel(root, &path) else { continue };
        let children = if is_dir { walk(root, &path, depth + 1)? } else { vec![] };
        nodes.push(FileNode { generated: !is_dir && is_generated(&name), name, path: rel, is_dir, children });
    }
    // Folders first, then case-insensitive by name.
    nodes.sort_by(|a, b| b.is_dir.cmp(&a.is_dir).then_with(|| a.name.to_lowercase().cmp(&b.name.to_lowercase())));
    Ok(nodes)
}

/// Picks the root document: a `.tex` with `\documentclass`, preferring
/// conventional names and shallow locations.
pub fn detect_main(root: &Path, tree: &[FileNode]) -> Option<String> {
    let mut candidates = Vec::new();
    collect_tex(tree, &mut candidates);
    let mut best: Option<(i32, String)> = None;
    for rel in candidates {
        let Ok(abs) = resolve(root, &rel) else { continue };
        let Ok(text) = fs::read_to_string(&abs) else { continue };
        let head: String = text.chars().take(20_000).collect();
        if !has_command(&head, "\\documentclass") {
            continue;
        }
        let stem = rel.rsplit('/').next().unwrap_or(&rel).trim_end_matches(".tex").to_lowercase();
        let mut score = 0;
        if head.contains("\\begin{document}") {
            score += 10;
        }
        if matches!(stem.as_str(), "main" | "thesis" | "paper" | "report" | "root" | "document" | "master") {
            score += 5;
        }
        score -= rel.matches('/').count() as i32 * 3;
        if best.as_ref().map_or(true, |(s, _)| score > *s) {
            best = Some((score, rel));
        }
    }
    best.map(|(_, r)| r)
}

/// True if `cmd` occurs outside a `%` comment.
fn has_command(text: &str, cmd: &str) -> bool {
    text.lines().any(|line| {
        let code = strip_comment(line);
        code.contains(cmd)
    })
}

fn strip_comment(line: &str) -> &str {
    let bytes = line.as_bytes();
    for i in 0..bytes.len() {
        if bytes[i] == b'%' && (i == 0 || bytes[i - 1] != b'\\') {
            return &line[..i];
        }
    }
    line
}

fn collect_tex(nodes: &[FileNode], out: &mut Vec<String>) {
    for n in nodes {
        if n.is_dir {
            collect_tex(&n.children, out);
        } else if n.name.to_lowercase().ends_with(".tex") {
            out.push(n.path.clone());
        }
    }
}

pub fn read_text(root: &Path, rel: &str) -> Result<String> {
    let abs = resolve(root, rel)?;
    let bytes = fs::read(&abs).map_err(|e| AppError::io("open", &abs, e))?;
    String::from_utf8(bytes).map_err(|_| {
        AppError::new(ErrorSource::FileSystem, format!("“{rel}” isn't a text file"))
            .hint("KernTeX can only edit UTF-8 text. If this is an older Latin-1 file, convert it to UTF-8 (most editors offer “Save with encoding”).")
    })
}

/// Atomic write: temp file + rename, so a crash never leaves a half-written file.
pub fn write_text(root: &Path, rel: &str, content: &str) -> Result<()> {
    let abs = resolve(root, rel)?;
    if let Some(parent) = abs.parent() {
        fs::create_dir_all(parent).map_err(|e| AppError::io("create the folder for", &abs, e))?;
    }
    let tmp = abs.with_extension(format!(
        "{}.kerntex-tmp",
        abs.extension().map(|e| e.to_string_lossy().into_owned()).unwrap_or_default()
    ));
    fs::write(&tmp, content).map_err(|e| AppError::io("save", &abs, e))?;
    fs::rename(&tmp, &abs).map_err(|e| {
        let _ = fs::remove_file(&tmp);
        AppError::io("save", &abs, e)
    })
}

pub fn create_file(root: &Path, rel: &str) -> Result<()> {
    let abs = resolve(root, rel)?;
    if abs.exists() {
        return Err(AppError::io("create", &abs, std::io::ErrorKind::AlreadyExists.into()));
    }
    write_text(root, rel, "")
}

pub fn create_dir(root: &Path, rel: &str) -> Result<()> {
    let abs = resolve(root, rel)?;
    fs::create_dir(&abs).map_err(|e| AppError::io("create the folder", &abs, e))
}

pub fn rename(root: &Path, from: &str, to: &str) -> Result<()> {
    let a = resolve(root, from)?;
    let b = resolve(root, to)?;
    if b.exists() {
        return Err(AppError::io("rename to", &b, std::io::ErrorKind::AlreadyExists.into()));
    }
    fs::rename(&a, &b).map_err(|e| AppError::io("rename", &a, e))
}

/// Moves to the system trash (recoverable) instead of deleting.
pub fn trash(root: &Path, rel: &str) -> Result<()> {
    let abs = resolve(root, rel)?;
    trash::delete(&abs).map_err(|e| {
        AppError::new(ErrorSource::FileSystem, format!("Couldn't move “{rel}” to the trash"))
            .detail(e.to_string())
            .hint("Close programs that may have the file open, then try again.")
    })
}

pub const TEMPLATE: &str = r"\documentclass[11pt]{article}
\usepackage[T1]{fontenc}
\usepackage{lmodern}
\usepackage{amsmath}
\usepackage{graphicx}
\usepackage[hidelinks]{hyperref}

\title{Untitled}
\author{}
\date{\today}

\begin{document}
\maketitle

\section{Introduction}
Welcome to \emph{KernTeX}. Edit this file and press \texttt{Ctrl+S} --- the
PDF on the right updates automatically.

\begin{equation}
  e^{i\pi} + 1 = 0
\end{equation}

\end{document}
";

/// Creates `parent/name/main.tex`; returns the new project root.
pub fn new_project(parent: &Path, name: &str) -> Result<PathBuf> {
    let name = name.trim();
    if name.is_empty() || name.contains(['/', '\\', ':', '*', '?', '"', '<', '>', '|']) {
        return Err(AppError::new(ErrorSource::App, "Invalid project name")
            .hint("Use letters, numbers, spaces, dashes or underscores — no slashes or special characters like : * ? \" < > |."));
    }
    let root = parent.join(name);
    if root.exists() {
        return Err(AppError::io("create the project", &root, std::io::ErrorKind::AlreadyExists.into()));
    }
    fs::create_dir_all(&root).map_err(|e| AppError::io("create the project", &root, e))?;
    write_text(&root, "main.tex", TEMPLATE)?;
    write_text(&root, ".gitignore", &format!("{BUILD_DIR}/\n"))?;
    Ok(root)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn tmp() -> PathBuf {
        let d = std::env::temp_dir().join(format!("kerntex-test-{}-{}", std::process::id(), rand_suffix()));
        fs::create_dir_all(&d).unwrap();
        d
    }
    fn rand_suffix() -> u128 {
        std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH).unwrap().as_nanos()
    }

    #[test]
    fn resolve_rejects_escapes() {
        let root = Path::new("/p");
        assert!(resolve(root, "../etc/passwd").is_err());
        assert!(resolve(root, "/etc/passwd").is_err());
        assert_eq!(resolve(root, "a/./b.tex").unwrap(), Path::new("/p/a/b.tex"));
    }

    #[test]
    fn detects_main_file() {
        let root = tmp();
        write_text(&root, "chapters/intro.tex", "\\section{Intro}").unwrap();
        write_text(&root, "old/draft.tex", "\\documentclass{article}\n\\begin{document}x\\end{document}").unwrap();
        write_text(&root, "thesis.tex", "% \\documentclass in a comment\n\\documentclass{report}\n\\begin{document}\\input{chapters/intro}\\end{document}").unwrap();
        write_text(&root, "notes.tex", "% \\documentclass{article}").unwrap();
        let info = open(&root).unwrap();
        assert_eq!(info.main_file.as_deref(), Some("thesis.tex"));
        fs::remove_dir_all(root).ok();
    }

    #[test]
    fn write_is_atomic_and_readable() {
        let root = tmp();
        write_text(&root, "a.tex", "hällo").unwrap();
        assert_eq!(read_text(&root, "a.tex").unwrap(), "hällo");
        assert!(!root.join("a.tex.kerntex-tmp").exists());
        fs::remove_dir_all(root).ok();
    }
}
