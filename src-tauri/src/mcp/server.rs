const NO_PROJECT: &str = "No project is open in KernTeX. Ask the user to open the project in KernTeX first.";
const READ_ONLY: &str = "The user has set AI assistants to read-only in KernTeX, so files can't be changed. You can still read files and compile. Ask the user to allow edits (Command palette → “AI assistants”) if changes are needed.";

pub(super) fn display_name(info: &Implementation) -> String {
    info.title.clone().filter(|t| !t.trim().is_empty()).unwrap_or_else(|| info.name.clone())
}

