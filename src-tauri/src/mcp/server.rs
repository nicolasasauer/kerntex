#[tool_router]
impl KernTexServer {
    pub fn new(hub: Arc<Hub>, client: u64) -> Self {
        Self { hub, client, tool_router: Self::tool_router() }
    }

    /// Lists the files of the project open in KernTeX, with the main document.
    #[tool(annotations(title = "List project files", read_only_hint = true, open_world_hint = false))]
    async fn list_files(&self, params: Parameters<ListFilesArgs>, ctx: RequestContext<RoleServer>) -> Result<Json<FileList>, String> {
        let args = params.0;
        let result = async {
            let project = self.begin(&ctx, false)?;
            let root = project.root.clone();
            let tree = blocking(move || project::read_tree(&root)).await?;
            let mut files = Vec::new();
            flatten(&tree, args.include_generated, &mut files);
            Ok(FileList { project: project.name, main_file: project.main_file, files })
        }
        .await;
        self.done("list_files", String::new(), result)
    }

    /// Reads a text file as the KernTeX editor shows it, including unsaved changes. Returns a `revision` for edit_file. Use start_line / end_line for long files.
    #[tool(annotations(title = "Read file", read_only_hint = true, open_world_hint = false))]
    async fn read_file(&self, params: Parameters<ReadFileArgs>, ctx: RequestContext<RoleServer>) -> Result<Json<FileText>, String> {
        let args = params.0;
        let detail = args.path.clone();
        let result = async {
            let project = self.begin(&ctx, false)?;
            let (path, _) = checked_path(&project, &args.path, false)?;
            let (text, unsaved) = self.current_text(&project, &path).await?;
            let lines: Vec<&str> = text.split_inclusive('\n').collect();
            let total = lines.len().max(1);
            let start = args.start_line.unwrap_or(1).max(1);
            let end = args.end_line.unwrap_or(total).min(total);
            if start > total {
                return Err(format!("start_line {start} is past the end of {path} ({total} lines)."));
            }
            let ranged = args.start_line.is_some() || args.end_line.is_some();
            let slice = if ranged { lines.get(start - 1..end.max(start - 1)).unwrap_or_default().concat() } else { text.clone() };
            if !ranged && slice.len() > MAX_READ_BYTES {
                return Err(format!(
                    "{path} is large ({} KB, {total} lines). Read it in parts with start_line and end_line.",
                    slice.len() / 1024
                ));
            }
            Ok(FileText {
                revision: edits::revision(&text),
                total_lines: total,
                start_line: start,
                end_line: end,
                unsaved_changes: unsaved,
                text: slice,
                path,
            })
        }
        .await;
        self.done("read_file", detail, result)
    }

    /// Changes an existing text file with targeted replacements. The change appears live in the user's editor and can be undone there (Ctrl+Z); KernTeX saves it with the user's next save, autosave or compile.
    #[tool(annotations(
        title = "Edit file",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = false
    ))]
    async fn edit_file(&self, params: Parameters<EditFileArgs>, ctx: RequestContext<RoleServer>) -> Result<Json<EditOutcome>, String> {
        let args = params.0;
        let detail = format!("{} ({} change{})", args.path, args.edits.len(), if args.edits.len() == 1 { "" } else { "s" });
        let result = async {
            let project = self.begin(&ctx, true)?;
            let (path, _) = checked_path(&project, &args.path, true)?;
            let (text, _) = self.current_text(&project, &path).await?;
            let current = edits::revision(&text);
            if let Some(expected) = &args.expected_revision {
                if expected != &current {
                    return Err(format!("{path} changed since you read it (now revision {current}), so nothing was changed. Read it again with read_file and redo the edit."));
                }
            }
            let new_text = edits::apply_edits(&path, &text, &args.edits).map_err(|e| describe(&e))?;
            self.hub.request("apply", json!({ "path": path, "base": text, "text": new_text }), UI_TIMEOUT).await?;
            Ok(EditOutcome {
                revision: edits::revision(&new_text),
                edits_applied: args.edits.len(),
                note: "Applied in the KernTeX editor; the user can undo it with Ctrl+Z. It's written to disk with the next save, autosave or compile.".into(),
                path,
            })
        }
        .await;
        self.done("edit_file", detail, result)
    }

    /// Creates a new text file (it must not exist yet). Missing folders are created.
    #[tool(annotations(
        title = "Create file",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = false,
        open_world_hint = false
    ))]
    async fn create_file(
        &self,
        params: Parameters<CreateFileArgs>,
        ctx: RequestContext<RoleServer>,
    ) -> Result<Json<CreateOutcome>, String> {
        let args = params.0;
        let detail = args.path.clone();
        let result = async {
            let project = self.begin(&ctx, true)?;
            let (path, abs) = checked_path(&project, &args.path, true)?;
            if abs.exists() {
                return Err(format!("{path} already exists. Use read_file and edit_file to change it."));
            }
            let (root, rel, content) = (project.root.clone(), path.clone(), args.content.clone());
            blocking(move || project::write_text(&root, &rel, &content)).await?;
            // Show it in the file tree; the file exists either way.
            let _ = self.hub.request("created", json!({ "path": path }), UI_TIMEOUT).await;
            Ok(CreateOutcome { revision: edits::revision(&args.content), path })
        }
        .await;
        self.done("create_file", detail, result)
    }

    /// Searches all text files of the project for a plain-text string (including unsaved editor changes).
    #[tool(annotations(title = "Search project", read_only_hint = true, open_world_hint = false))]
    async fn search(&self, params: Parameters<SearchArgs>, ctx: RequestContext<RoleServer>) -> Result<Json<SearchResult>, String> {
        let args = params.0;
        let detail = format!("“{}”", args.query);
        let result = async {
            let project = self.begin(&ctx, false)?;
            if args.query.is_empty() {
                return Err("query is empty.".into());
            }
            let buffers = self.hub.request("buffers", json!({}), UI_TIMEOUT).await?;
            let buffers: std::collections::HashMap<String, String> =
                serde_json::from_value(buffers.get("buffers").cloned().unwrap_or(Value::Null)).unwrap_or_default();
            let max = args.max_results.unwrap_or(100).clamp(1, 500);
            let root = project.root.clone();
            blocking(move || {
                let tree = project::read_tree(&root)?;
                let mut files = Vec::new();
                flatten(&tree, false, &mut files);
                let mut hits = Vec::new();
                let mut searched = 0;
                let mut truncated = false;
                for f in files {
                    let text = match buffers.get(&f.path) {
                        Some(t) => t.clone(),
                        None => {
                            let Ok(abs) = project::resolve(&root, &f.path) else { continue };
                            if std::fs::metadata(&abs).map(|m| m.len() > MAX_SEARCH_FILE_BYTES).unwrap_or(true) {
                                continue;
                            }
                            match project::read_text(&root, &f.path) {
                                Ok(t) => t,
                                Err(_) => continue, // binary file
                            }
                        }
                    };
                    searched += 1;
                    if !edits::search_text(&f.path, &text, &args.query, args.case_sensitive, max, &mut hits) {
                        truncated = true;
                        break;
                    }
                }
                Ok(SearchResult { hits, truncated, files_searched: searched })
            })
            .await
        }
        .await;
        self.done("search", detail, result)
    }

    /// Saves all open files and compiles the main document, like the Compile button. Returns errors and warnings with file, line and a hint how to fix them.
    #[tool(annotations(
        title = "Compile",
        read_only_hint = false,
        destructive_hint = false,
        idempotent_hint = true,
        open_world_hint = false
    ))]
    async fn compile(&self, ctx: RequestContext<RoleServer>) -> Result<Json<CompileReport>, String> {
        let result = async {
            self.begin(&ctx, false)?;
            let generation = self.hub.compile_generation();
            let mut progress = self.hub.subscribe_progress();
            let token = ctx.meta.get_progress_token();
            let request = self.hub.request("compile", json!({}), COMPILE_TIMEOUT);
            tokio::pin!(request);
            let mut step = 0.0;
            let answer = loop {
                tokio::select! {
                    answer = &mut request => break answer,
                    Ok(p) = progress.recv() => {
                        if let Some(token) = &token {
                            step += 1.0;
                            let message = match &p.detail { Some(d) => format!("{} – {d}", p.stage), None => p.stage.clone() };
                            let _ = ctx.peer.notify_progress(ProgressNotificationParam::new(token.clone(), step).with_message(message)).await;
                        }
                    }
                    _ = ctx.ct.cancelled() => return Err("The compile request was cancelled by the client.".to_string()),
                }
            }?;
            self.hub.compile_since(generation).ok_or_else(|| {
                answer.get("message").and_then(Value::as_str).unwrap_or("KernTeX didn't compile. Check that the project has a main file.").to_string()
            })
        }
        .await;
        let detail = match &result {
            Ok(r) if r.canceled => "stopped".to_string(),
            Ok(r) => format!(
                "{} error{}, {} warning{}",
                r.errors,
                if r.errors == 1 { "" } else { "s" },
                r.warnings,
                if r.warnings == 1 { "" } else { "s" }
            ),
            Err(_) => String::new(),
        };
        self.done("compile", detail, result)
    }

    /// Errors and warnings of the last compile (by the user or an agent), with file, line and a hint how to fix each.
    #[tool(annotations(title = "Get diagnostics", read_only_hint = true, open_world_hint = false))]
    async fn get_diagnostics(&self, ctx: RequestContext<RoleServer>) -> Result<Json<CompileReport>, String> {
        let result = async {
            self.begin(&ctx, false)?;
            self.hub.last_compile().ok_or_else(|| "The project hasn't been compiled since it was opened. Call compile first.".to_string())
        }
        .await;
        self.done("get_diagnostics", String::new(), result)
    }
}

#[tool_handler]
impl ServerHandler for KernTexServer {
    fn get_info(&self) -> ServerConfig {
        let mut info = Implementation::new("kerntex", env!("CARGO_PKG_VERSION"));
        info.title = Some("KernTeX".into());
        info.website_url = Some("https://kerntex.nicolas-iot.eu".into());
        ServerConfig::new(ServerCapabilities::builder().enable_tools().build()).with_server_info(info).with_instructions(INSTRUCTIONS)
    }
}

impl KernTexServer {
    /// Common checks for every tool: who's calling, rate limit, permissions, open project.
    fn begin(&self, ctx: &RequestContext<RoleServer>, writes: bool) -> Result<Project, String> {
        if let Some(info) = ctx.client_info() {
            self.hub.name_client(self.client, &display_name(&info));
        }
        if !self.hub.allow_call(self.client) {
            return Err("Too many requests in a short time. Wait a minute, then continue.".into());
        }
        let config = self.hub.config();
        if !config.enabled {
            return Err(DISABLED.into());
        }
        if writes && !config.allow_edits {
            return Err(READ_ONLY.into());
        }
        config.project.ok_or_else(|| NO_PROJECT.to_string())
    }

    /// Reports the call to the activity list and passes the result through.
    fn done<T>(&self, tool: &str, detail: String, result: Result<T, String>) -> Result<Json<T>, String> {
        self.hub.activity(self.client, tool, &detail, result.as_ref().err().map(String::as_str));
        result.map(Json)
    }

    /// The text the editor shows (unsaved changes included), else the file on disk.
    async fn current_text(&self, project: &Project, path: &str) -> Result<(String, bool), String> {
        let open = self.hub.request("read", json!({ "path": path }), UI_TIMEOUT).await?;
        if let Some(text) = open.get("text").and_then(Value::as_str) {
            return Ok((text.to_string(), open.get("dirty").and_then(Value::as_bool).unwrap_or(false)));
        }
        let (root, rel) = (project.root.clone(), path.to_string());
        Ok((blocking(move || project::read_text(&root, &rel)).await?, false))
    }
}

/// Normalizes an agent-supplied path and checks it stays inside the project.
/// Writes into `.git` and KernTeX's build folder are refused.
fn checked_path(project: &Project, raw: &str, writes: bool) -> Result<(String, PathBuf), String> {
    let rel = raw.trim().replace('\\', "/");
    let rel = rel.trim_start_matches("./").trim_end_matches('/').to_string();
    if rel.is_empty() {
        return Err("path is empty. Use a path relative to the project root, e.g. main.tex (list_files shows all files).".into());
    }
    let abs = project::resolve(&project.root, &rel).map_err(|e| describe(&e))?;
    let first = rel.split('/').next().unwrap_or_default();
    if writes && (first == ".git" || first == BUILD_DIR) {
        return Err(format!("{rel} is in a folder KernTeX manages ({first}); it can't be changed by an agent."));
    }
    // Symlinks must not lead out of the project.
    if let (Ok(root), Some(existing)) = (project.root.canonicalize(), abs.ancestors().find(|p| p.exists())) {
        if let Ok(real) = existing.canonicalize() {
            if !real.starts_with(&root) {
                return Err(format!("{rel} points outside the project folder (through a link), so it was refused."));
            }
        }
    }
    Ok((rel, abs))
}

fn flatten(nodes: &[FileNode], include_generated: bool, out: &mut Vec<FileEntry>) {
    for n in nodes {
        if n.is_dir {
            flatten(&n.children, include_generated, out);
        } else if include_generated || !n.generated {
            out.push(FileEntry { path: n.path.clone(), generated: n.generated });
        }
    }
}

/// Runs blocking file work off the async runtime.
async fn blocking<T: Send + 'static>(f: impl FnOnce() -> crate::core::error::Result<T> + Send + 'static) -> Result<T, String> {
    match tokio::task::spawn_blocking(f).await {
        Ok(r) => r.map_err(|e| describe(&e)),
        Err(e) => Err(format!("Internal error in KernTeX: {e}")),
    }
}
